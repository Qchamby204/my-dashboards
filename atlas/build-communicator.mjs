// Crucible remains the curriculum source. Compile its data and views into the
// Communicator runtime, with no iframe, second navigation shell, or new records.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
const original=await readFile(new URL('crucible.html',root),'utf8');
let core=original.match(/<script type="text\/plain" data-crucible-curriculum>\s*'use strict';([\s\S]*?)<\/script>/)[1].split('/* --- Router ')[0];
core=core.replace('let state = loadState();','let state = defaultState();');
const adapter=await readFile(new URL('atlas/crucible-adapter.js',root),'utf8');
await writeFile(new URL('shared/communicator-curriculum.js',root),'// Generated by atlas/build-communicator.mjs from crucible.html.\n(()=>{\n'+core+'\n'+adapter+'\n})();\n');
function scopeCSS(css){
  let out='',position=0;
  while(position<css.length){
    const open=css.indexOf('{',position);if(open<0)break;
    let depth=1,end=open+1;while(depth&&end<css.length){if(css[end]==='{')depth++;if(css[end]==='}')depth--;end++;}
    const selector=css.slice(position,open).trim(),body=css.slice(open+1,end-1);
    if(selector.startsWith('@media'))out+=selector+'{'+scopeCSS(body)+'}\n';
    else if(!selector.startsWith('@'))out+=selector.split(',').map(s=>'.communicator-analysis '+s.trim().replace(/^:root$|^body$/,'')).join(',')+'{'+body+'}\n';
    position=end;
  }
  return out;
}
const css=original.match(/<style>([\s\S]*?)<\/style>/)[1].replace(/\/\*[\s\S]*?\*\//g,'').replace(/@import\s+url\([^)]*\);/g,'');
await writeFile(new URL('shared/communicator-curriculum.css',root),'/* Generated, scoped curriculum styles. */\n'+scopeCSS(css));
const theme=await readFile(new URL('shared/atlas-theme.js',root),'utf8');
const version=createHash('sha256').update(await readFile(new URL('shared/communication-enhancements.js',root))).digest('hex').slice(0,12);
await writeFile(new URL('shared/communicator-theme.js',root),'// Generated Communicator entry from shared/atlas-theme.js.\n'+theme.replace(/communication-enhancements\.js\?v=[a-z0-9]+/g,'communication-enhancements.js?v='+version));
let html=await readFile(new URL('communication-trainer.html',root),'utf8');
for(const asset of ['communicator-theme.js','communicator-curriculum.js','communicator-curriculum.css','communicator-integration.js','communicator-integration.css']){
  const hash=createHash('sha256').update(await readFile(new URL('shared/'+asset,root))).digest('hex').slice(0,12);
  const pattern=new RegExp('shared/'+asset.replaceAll('.','\\.')+'(?:\\?v=[a-zA-Z0-9-]+)?','g');
  html=html.replace(pattern,'shared/'+asset+'?v='+hash);
}
await writeFile(new URL('communication-trainer.html',root),html);
